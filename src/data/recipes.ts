  recipes.find((r) => r.id === id);

export const getRecipesByCategory = (
  category: Recipe["category"]
): Recipe[] => recipes.filter((r) => r.category === category);

export const getKetoRecipes = (minScore = 4): Recipe[] =>
  recipes.filter((r) => r.ketoScore >= minScore);

export const getHighProteinRecipes = (minScore = 4): Recipe[] =>
  recipes.filter((r) => r.proteinScore >= minScore);
